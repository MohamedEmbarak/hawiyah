// Writes the results of the example compilation (<id> is the page key in its path form:
// a guide guide.<id>, a template template.<id>, scripts/content/kinds.mjs):
//   <framesDir>/<id>/<lang>/<example>/<framework>.json   one payload per framework
//   <generatedDir>/<id>/<lang>/<example>.ts             native Angular example components
//   <generatedDir>/<id>/<lang>/index.ts                 { examples: { [example]: Class } }
//   <generatedDir>/<id>/<lang>/listings.json            highlighted listings of every group
//   <generatedDir>/loaders.ts                           { '<id>/<lang>': () => import('./<id>/<lang>/index') }
//                                                       and the listings loaders
// Both directories are recreated, so no output of a removed group stays behind.
import { join } from 'node:path';
import { highlight } from '../content/highlight.mjs';
import { pathKey } from '../content/kinds.mjs';
import { resetDir, writeFile } from './modules.mjs';

const HEADER = '// Generated by scripts/examples (build step 25-examples). Do not edit.\n';

export function payloadPath(framesDir, payload) {
  return join(framesDir, pathKey(payload.id), payload.lang, payload.example, `${payload.framework}.json`);
}

export function writePayloads(payloads, framesDir) {
  resetDir(framesDir);
  for (const payload of payloads) writeFile(payloadPath(framesDir, payload), `${JSON.stringify(payload, null, 2)}\n`);
}

const quote = (value) => `'${value.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;

/** Files of a payload the page block lists: the primary file, and main.js for vanilla. */
export function listedFiles(payload) {
  const names = [payload.primaryFile];
  if (payload.framework === 'vanilla' && 'main.js' in payload.files && payload.primaryFile !== 'main.js') names.push('main.js');
  return names.filter((name) => name in payload.files);
}

/** Highlighter language of a file name (null: plain text). */
export function listingLanguage(fileName) {
  const extension = /\.([a-z]+)$/.exec(fileName)?.[1] ?? '';
  return ['html', 'vue', 'ts', 'tsx', 'js', 'jsx', 'css'].includes(extension) ? extension : null;
}

/**
 * Highlighted listings of the payloads, by '<id>/<lang>':
 * { [example]: { [framework]: [{ fileName, text, lines }] } }, highlighted with the
 * content pipeline's highlighter (scripts/content/highlight.mjs) at build time.
 */
export function listingsOf(payloads) {
  const pages = new Map();
  for (const payload of payloads) {
    const key = `${payload.id}/${payload.lang}`;
    if (!pages.has(key)) pages.set(key, {});
    const page = pages.get(key);
    page[payload.example] ??= {};
    page[payload.example][payload.framework] = listedFiles(payload).map((fileName) => {
      const text = payload.files[fileName] ?? '';
      return { fileName, text, lines: highlight(listingLanguage(fileName), text) };
    });
  }
  return pages;
}

/** Source of src/generated/examples/loaders.ts for the given '<id>/<lang>' keys. */
export function loadersSource(keys, listingKeys = []) {
  const lines = [...keys].sort().map((key) => `  ${quote(key)}: () => import(${quote(`./${pathKey(key)}/index`)}),`);
  const listingLines = [...listingKeys].sort().map((key) => `  ${quote(key)}: () => import(${quote(`./${pathKey(key)}/listings.json`)}),`);
  return `${HEADER}import type { Type } from '@angular/core';

/** Native Angular example components of one page and language, by example name. */
export interface NativeExampleIndex {
  examples: Readonly<Record<string, Type<unknown>>>;
}

/** '<id>/<lang>' to a lazy import of src/generated/examples/<id>/<lang>/index.ts. */
export const exampleLoaders: Readonly<Record<string, () => Promise<NativeExampleIndex>>> = {
${lines.join('\n')}${lines.length ? '\n' : ''}};

/** '<id>/<lang>' to a lazy import of src/generated/examples/<id>/<lang>/listings.json. */
export const exampleListingLoaders: Readonly<Record<string, () => Promise<{ default: unknown }>>> = {
${listingLines.join('\n')}${listingLines.length ? '\n' : ''}};

export default exampleLoaders;
`;
}

/** Source of src/generated/examples/<id>/<lang>/index.ts. */
export function indexSource(natives) {
  const sorted = [...natives].sort((a, b) => a.example.localeCompare(b.example));
  const imports = sorted.map((n) => `import { ${n.className} } from ${quote(`./${n.example}`)};`).join('\n');
  const entries = sorted.map((n) => `  ${quote(n.example)}: ${n.className},`).join('\n');
  return `${HEADER}import type { Type } from '@angular/core';
${imports}

export const examples: Readonly<Record<string, Type<unknown>>> = {
${entries}
};

export default examples;
`;
}

export function writeGenerated(natives, generatedDir, payloads = []) {
  resetDir(generatedDir);
  const byPage = new Map();
  for (const native of natives) {
    const key = `${native.id}/${native.lang}`;
    if (!byPage.has(key)) byPage.set(key, []);
    byPage.get(key).push(native);
    writeFile(join(generatedDir, pathKey(native.id), native.lang, `${native.example}.ts`), `${HEADER}${native.source}`);
  }
  for (const [key, list] of byPage) writeFile(join(generatedDir, pathKey(key), 'index.ts'), indexSource(list));
  const listings = listingsOf(payloads);
  for (const [key, page] of listings) writeFile(join(generatedDir, pathKey(key), 'listings.json'), `${JSON.stringify(page)}\n`);
  writeFile(join(generatedDir, 'loaders.ts'), loadersSource(byPage.keys(), listings.keys()));
  return { pages: byPage.size, components: natives.length, listings: listings.size };
}

// Writes the results of the example compilation:
//   <framesDir>/<id>/<lang>/<example>/<framework>.json   one payload per framework
//   <generatedDir>/<id>/<lang>/<example>.ts             native Angular example components
//   <generatedDir>/<id>/<lang>/index.ts                 { examples: { [example]: Class } }
//   <generatedDir>/loaders.ts                           { '<id>/<lang>': () => import('./<id>/<lang>/index') }
// Both directories are recreated, so no output of a removed group stays behind.
import { join } from 'node:path';
import { resetDir, writeFile } from './modules.mjs';

const HEADER = '// Generated by scripts/examples (build step 25-examples). Do not edit.\n';

export function payloadPath(framesDir, payload) {
  return join(framesDir, payload.id, payload.lang, payload.example, `${payload.framework}.json`);
}

export function writePayloads(payloads, framesDir) {
  resetDir(framesDir);
  for (const payload of payloads) writeFile(payloadPath(framesDir, payload), `${JSON.stringify(payload, null, 2)}\n`);
}

const quote = (value) => `'${value.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;

/** Source of src/generated/examples/loaders.ts for the given '<id>/<lang>' keys. */
export function loadersSource(keys) {
  const lines = [...keys].sort().map((key) => `  ${quote(key)}: () => import(${quote(`./${key}/index`)}),`);
  return `${HEADER}import type { Type } from '@angular/core';

/** Native Angular example components of one page and language, by example name. */
export interface NativeExampleIndex {
  examples: Readonly<Record<string, Type<unknown>>>;
}

/** '<id>/<lang>' to a lazy import of src/generated/examples/<id>/<lang>/index.ts. */
export const exampleLoaders: Readonly<Record<string, () => Promise<NativeExampleIndex>>> = {
${lines.join('\n')}${lines.length ? '\n' : ''}};

export default exampleLoaders;
`;
}

/** Source of src/generated/examples/<id>/<lang>/index.ts. */
export function indexSource(natives) {
  const sorted = [...natives].sort((a, b) => a.example.localeCompare(b.example));
  const imports = sorted.map((n) => `import { ${n.className} } from ${quote(`./${n.example}`)};`).join('\n');
  const entries = sorted.map((n) => `  ${quote(n.example)}: ${n.className},`).join('\n');
  return `${HEADER}import type { Type } from '@angular/core';
${imports}

export const examples: Readonly<Record<string, Type<unknown>>> = {
${entries}
};

export default examples;
`;
}

export function writeGenerated(natives, generatedDir) {
  resetDir(generatedDir);
  const byPage = new Map();
  for (const native of natives) {
    const key = `${native.id}/${native.lang}`;
    if (!byPage.has(key)) byPage.set(key, []);
    byPage.get(key).push(native);
    writeFile(join(generatedDir, native.id, native.lang, `${native.example}.ts`), `${HEADER}${native.source}`);
  }
  for (const [key, list] of byPage) writeFile(join(generatedDir, key, 'index.ts'), indexSource(list));
  writeFile(join(generatedDir, 'loaders.ts'), loadersSource(byPage.keys()));
  return { pages: byPage.size, components: natives.length };
}
